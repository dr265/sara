# actions/word_document.py
"""
Word document creation for SARA.
Ported from Brahma-Echo (actions/docx_tools.py), adapted to SARA's action
contract and llm_client. Creates real .docx files (letters, reports, notes)
via python-docx and VERIFIES by reopening the saved file.
"""

from datetime import datetime
from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt, RGBColor

ACCENT = RGBColor(0x0A, 0x6E, 0xA8)


def _output_dir() -> Path:
    d = Path.home() / "Documents" / "SARA Docs"
    d.mkdir(parents=True, exist_ok=True)
    return d


def _safe_name(title: str) -> str:
    keep = [c if c.isalnum() or c in " -_" else "_" for c in title]
    return ("".join(keep).strip() or "document")[:60]


def _add_body(doc: Document, content: str) -> None:
    """Content is plain text. '## ' prefix = heading, '- ' = bullet,
    otherwise paragraph."""
    for raw in (content or "").splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("## "):
            h = doc.add_heading(line[3:].strip(), level=1)
            for run in h.runs:
                run.font.color.rgb = ACCENT
        elif line.startswith("# "):
            h = doc.add_heading(line[2:].strip(), level=0)
        elif line.startswith("- ") or line.startswith("• "):
            doc.add_paragraph(line[2:].strip(), style="List Bullet")
        else:
            doc.add_paragraph(line)


def word_document(parameters: dict, player=None) -> str:
    p = parameters or {}
    action = (p.get("action") or "create").lower().strip()
    title = (p.get("title") or "Document").strip()
    content = (p.get("content") or "").strip()
    author = (p.get("author") or "").strip()
    kind = (p.get("type") or "generic").lower().strip()   # letter | report | generic

    if action not in ("create", "new", "write"):
        return f"Unknown word_document action: '{action}'."

    if not content:
        return "No content given — tell me what the document should contain."

    doc = Document()

    # core properties
    try:
        doc.core_properties.title = title
        doc.core_properties.author = author or "SARA"
        doc.core_properties.created = datetime.now()
    except Exception:
        pass

    if kind == "letter":
        # sender block, date, body, signature
        doc.add_paragraph(datetime.now().strftime("%B %d, %Y"))
        doc.add_paragraph()
        _add_body(doc, content)
        doc.add_paragraph()
        sig = doc.add_paragraph(author or "Yours sincerely")
        sig.alignment = WD_ALIGN_PARAGRAPH.LEFT
    else:
        h = doc.add_heading(title, level=0)
        for run in h.runs:
            run.font.color.rgb = ACCENT
        meta = doc.add_paragraph()
        meta_run = meta.add_run(f"Generated by SARA — {datetime.now():%Y-%m-%d %H:%M}")
        meta_run.font.size = Pt(9)
        meta_run.font.italic = True
        doc.add_paragraph()
        if kind == "report":
            # cover-ish first page break
            doc.add_page_break()
        _add_body(doc, content)

    out = _output_dir() / f"{_safe_name(title)} {datetime.now():%Y%m%d %H%M}.docx"
    doc.save(str(out))

    # ── verify by reopening ─────────────────────────────────────────────────
    try:
        check = Document(str(out))
        n_paras = len(check.paragraphs)
        assert n_paras > 1
        return f"Word document created and verified: {out} ({n_paras} paragraphs)."
    except Exception as e:
        return f"Document was written but verification failed: {e} — path: {out}"


