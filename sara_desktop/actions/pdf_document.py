# actions/pdf_document.py
"""
PDF creation and manipulation for SARA.
Ported from Brahma-Echo (actions/pdf_tools.py), adapted to SARA's action
contract. Creates styled PDF reports via reportlab and merges/splits via
pypdf, then VERIFIES by reopening the output.
"""

from datetime import datetime
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_JUSTIFY, TA_LEFT
from reportlab.lib.pagesizes import LETTER
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (
    PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle,
)

try:
    from pypdf import PdfReader, PdfWriter   # pypdf (modern)
except ImportError:
    try:
        from PyPDF2 import PdfReader, PdfWriter   # PyPDF2 (installed)
    except ImportError:
        PdfReader = PdfWriter = None

ACCENT = colors.HexColor("#0A6EA8")
MUTED = colors.HexColor("#6B7A8C")


def _output_dir() -> Path:
    d = Path.home() / "Documents" / "SARA Docs"
    d.mkdir(parents=True, exist_ok=True)
    return d


def _safe_name(title: str) -> str:
    keep = [c if c.isalnum() or c in " -_" else "_" for c in title]
    return ("".join(keep).strip() or "document")[:60]


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(MUTED)
    canvas.drawString(inch, 0.6 * inch, f"Generated by SARA — {datetime.now():%Y-%m-%d %H:%M}")
    canvas.drawRightString(LETTER[0] - inch, 0.6 * inch, f"Page {doc.page}")
    canvas.restoreState()


def _body_styles():
    ss = getSampleStyleSheet()
    return (
        ParagraphStyle("SaraTitle", parent=ss["Title"], fontSize=24, textColor=ACCENT, spaceAfter=6),
        ParagraphStyle("SaraH1", parent=ss["Heading1"], fontSize=15, textColor=ACCENT,
                       spaceBefore=14, spaceAfter=4),
        ParagraphStyle("SaraBody", parent=ss["BodyText"], fontSize=10.5, leading=15,
                       alignment=TA_JUSTIFY, spaceAfter=6),
        ParagraphStyle("SaraMeta", parent=ss["Normal"], fontSize=8.5, textColor=MUTED,
                       alignment=TA_LEFT, spaceAfter=14),
        ParagraphStyle("SaraBullet", parent=ss["BodyText"], fontSize=10.5, leading=15,
                       leftIndent=16, bulletIndent=6, spaceAfter=3),
    )


def _escape(text: str) -> str:
    return (text or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _build_pdf(out_path: Path, title: str, content: str) -> None:
    doc = SimpleDocTemplate(
        str(out_path), pagesize=LETTER,
        leftMargin=inch, rightMargin=inch, topMargin=0.9 * inch, bottomMargin=0.9 * inch,
        title=title, author="SARA",
    )
    st_title, st_h1, st_body, st_meta, st_bullet = _body_styles()
    story = [
        Paragraph(_escape(title), st_title),
        Paragraph(f"{datetime.now():%A, %B %d, %Y}", st_meta),
    ]

    table_buf: list[list[str]] = []
    in_table = False

    def flush_table():
        nonlocal table_buf, in_table
        if not table_buf:
            in_table = False
            return
        data = [[Paragraph(_escape(c), st_body) for c in row] for row in table_buf]
        col_count = max(len(r) for r in table_buf)
        width = (LETTER[0] - 2 * inch) / col_count
        tbl = Table(data, colWidths=[width] * col_count, hAlign="LEFT")
        tbl.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), ACCENT),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#B9C4CE")),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#EFF4F8")]),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        story.append(tbl)
        story.append(Spacer(1, 10))
        table_buf = []
        in_table = False

    for raw in (content or "").splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("|") and line.count("|") >= 2:
            cells = [c.strip() for c in line.strip("|").split("|")]
            if all(set(c) <= set("-: ") for c in cells):
                continue   # markdown separator row
            table_buf.append(cells)
            in_table = True
            continue
        if in_table:
            flush_table()
        if line.startswith("# "):
            story.append(Paragraph(_escape(line[2:].strip()), st_title))
        elif line.startswith("## "):
            story.append(Paragraph(_escape(line[3:].strip()), st_h1))
        elif line.startswith("- ") or line.startswith("• "):
            story.append(Paragraph(_escape(line[2:].strip()), st_bullet, bulletText="•"))
        else:
            story.append(Paragraph(_escape(line), st_body))
    flush_table()

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)


def pdf_document(parameters: dict, player=None) -> str:
    p = parameters or {}
    action = (p.get("action") or "create").lower().strip()
    title = (p.get("title") or "Document").strip()
    content = (p.get("content") or "").strip()
    files = p.get("files") or []
    output = (p.get("output") or "").strip()

    if action in ("create", "new", "write"):
        if not content:
            return "No content given — pass the report text via 'content'."
        out = _output_dir() / f"{_safe_name(title)} {datetime.now():%Y%m%d %H%M}.pdf"
        _build_pdf(out, title, content)
        try:
            reader = PdfReader(str(out))
            n = len(reader.pages)
            assert n >= 1
            return f"PDF created and verified: {out} ({n} page{'s' if n != 1 else ''})."
        except Exception as e:
            return f"PDF written but verification failed: {e} — path: {out}"

    elif action in ("merge", "combine"):
        if PdfReader is None:
            return "pypdf is not installed — cannot merge."
        if len(files) < 2:
            return "Provide at least two PDF paths in 'files' to merge."
        try:
            writer = PdfWriter()
            total = 0
            for f in files:
                reader = PdfReader(f)
                for pg in reader.pages:
                    writer.add_page(pg)
                    total += 1
            out = _output_dir() / f"{_safe_name(output or 'Merged')} {datetime.now():%Y%m%d %H%M}.pdf"
            with open(out, "wb") as fh:
                writer.write(fh)
            return f"Merged {len(files)} PDFs ({total} pages) into: {out}"
        except Exception as e:
            return f"Merge failed: {e}"

    elif action in ("split", "extract"):
        if PdfReader is None:
            return "pypdf is not installed — cannot split."
        if not files:
            return "Provide the PDF path in 'files'."
        try:
            reader = PdfReader(files[0])
            n = len(reader.pages)
            out_dir = _output_dir()
            written = []
            base = _safe_name(Path(files[0]).stem)
            for i, pg in enumerate(reader.pages, 1):
                w = PdfWriter()
                w.add_page(pg)
                single = out_dir / f"{base} page {i}.pdf"
                with open(single, "wb") as fh:
                    w.write(fh)
                written.append(single.name)
            return f"Split {n} pages into {len(written)} files in {out_dir}"
        except Exception as e:
            return f"Split failed: {e}"

    return f"Unknown pdf action: '{action}'."


